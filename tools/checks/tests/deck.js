// tools/checks/tests/deck.js: YOUR DECK (engine/deck.js). The dev screen: it opens and draws, and power goes to the
// oldest chips first, so the chip you just slotted is the one with none. The real deck: you get it at USER, it lives
// in save.deck, its mk comes from THE BOARD's posts, and its switches turn posts off for your runs.
module.exports = { name: 'deck', body: `
  openDeck({ dev: true }); await sleep(400);
  check(st.mode === 'panel' && st.panelFn === deckLines, 'it opens as a full panel');
  check(buildScene(performance.now(), false).length > 300, 'it draws');
  const p0 = deckPower();
  check(p0.budget === 6 && p0.used === 5 && !p0.off.length, 'starts at 5 of 6, all on: ' + JSON.stringify([p0.used, p0.budget, p0.off]));
  deckSlot('MK7', 'SH3');
  let p = deckPower();
  check(p.off.length === 1 && p.off[0] === 'SH3', 'the newest chip is the one with no power: ' + JSON.stringify(p.off));
  check(DECK.slots.SH3 === 'MK7', 'it still goes in');
  deckSlot('LS1', 'SH4');
  p = deckPower();
  check(p.on.has('SH4') && p.off.length === 1, 'a newer, cheaper chip still gets what is left: ' + JSON.stringify([...p.on]));
  deckSlot('LI2', 'PSU');
  p = deckPower();
  check(p.budget === 9 && !p.off.length, 'a bigger cell lights them all: ' + JSON.stringify(p.off));
  deckSlot('SC1', 'PSU');
  p = deckPower();
  check(p.off.includes('SH3') && !p.off.includes('BT1'), 'back to the small cell: the newest go dark first: ' + JSON.stringify(p.off));
  deckSlot('ST4', 'BT2');
  check(DECK.slots.BT2 === 'ST4' && !DECK.slots.BT1, 'a chip moves (one of each)');
  deckPick('BT1'); check(DECK.pick && DECK.pick.id === 'BT1', 'the picker opens');
  check(buildScene(performance.now(), false).length > 300, 'the picker draws');
  deckPick('OV1'); check(DECK.pick.id === 'BT1', 'a locked socket has no picker');
  DECK.pick = null; deckPick('SH4'); buildScene(performance.now(), false);
  check(DECK.pick.sel === 'LS1', 'the picker starts on the chip in the socket: ' + DECK.pick.sel);
  DECK.pick.keys.move(1); check(DECK.pick.sel !== 'LS1' && DECK.pick, 'the keys move the pick, it stays open');
  const next = DECK.pick.sel; DECK.pick.keys.go(); check(!DECK.pick && DECK.slots.SH4 === next, 'go slots it and closes: ' + DECK.slots.SH4);
  deckPick('SH3'); buildScene(performance.now(), false);
  const row = id => hits.find(h => h.id === id);
  render(performance.now()); const r = row('dkk_PG2') || row('dkk_CD2'), want = r && r.id.slice(4);
  r.onTap(); check(DECK.pick && DECK.pick.sel === want, 'one tap picks: ' + want);
  r.onTap(); check(!DECK.pick && DECK.slots.SH3 === want, 'a second tap slots it and closes: ' + DECK.slots.SH3);
  deckTapPart('rom'); check(DECK.sel.kind === 'part' && DECK.sel.id === 'cpu', 'the ROM pins select the CPU');
  deckTapPart('cpu'); check(DECK.cpu && !DECK.pick, 'a second tap opens the CPU popup');
  check(buildScene(performance.now(), false).length > 300, 'the CPU popup draws');
  const was = DECK.nemesis; render(performance.now()); const nb = hits.find(h => h.id === 'dksweemesis' || h.id === 'dkswnemesis'); nb.onTap();
  check(DECK.nemesis !== was, 'NEMESIS cycles to the next corp: ' + was + ' > ' + DECK.nemesis);
  const tb = hits.find(h => h.id === 'dkswstray'); tb.onTap(); check(!DECK.sw.has('stray'), 'a switch turns off');
  deckKey('escape'); check(!DECK.cpu, 'Escape closes it');
  DECK.scroll = 0; deckCarry('GD0'); check(!DECK.carry, 'a chip with no open socket: no carry');
  deckCarry('HN2'); check(!DECK.carry, 'HEAT (mk IV) has no open socket yet');
  DECK.mk = 3; DECK.scroll = 0; deckCarry('GR8');
  check(DECK.carry === 'GR8' && DECK.scroll + deckViewRows() >= 38 && DECK.scroll <= 34, 'SLOT scrolls the OVERVOLT sockets into view: ' + DECK.scroll);
  // the FUSE is mk IV's own power: chips there don't use the cell
  DECK.mk = 4; DECK.fuse = true; DECK.blown = false;
  const c0 = deckPower().used; deckSlot('GD0', 'SU1'); deckSlot('OMNI', 'BS1');
  const pf = deckPower();
  check(pf.fuse && pf.fuse.used === 6 && pf.fuse.budget === DECK_FUSE_PWR && pf.used === c0, 'mk IV runs on the fuse, not the cell: ' + JSON.stringify(pf.fuse) + ' cell ' + pf.used);
  DECK.blown = true; check(deckPower().fuse === null && deckPower().used === c0, 'a blown fuse: mk IV dark, the cell unchanged');
  DECK = null; DECK_DEV = null;

  // ---- the real deck
  const keep = JSON.stringify(save);
  save.legacy = {}; save.deck = null; save.rep = 5000; save.nemesis = null; CALL_QUEUE.length = 0;
  deckEnsure(); check(!save.deck, 'GUEST: no deck yet');
  for (const k of ['hard', 'cash', 'kit', 'belt']) save.legacy[k] = 1;
  boardLevelNews(2);
  check(save.deck && save.deck.slots.PSU === 'SC1' && save.deck.chips.SP3 === 1, 'USER: the deck is yours, with its cell and SPOILS: ' + JSON.stringify(save.deck && save.deck.slots));
  check(CALL_QUEUE.some(c => c.who === 'pops' && c.btn), 'POPS calls about it, with a button to see it');
  FEAT_QUEUE.length = 0; CALL_QUEUE.length = 0;
  openDeck(); await sleep(300);
  check(DECK.real && DECK.mk === 2 && deckOwned().length === 2, 'it opens the real deck: mk II, your 2 chips: ' + deckOwned());
  check(buildScene(performance.now(), false).length > 300, 'the real deck draws');
  deckPull('SPL'); buildScene(performance.now(), false);
  check(!save.deck.slots.SPL && save.deck.order.join() === 'PSU', 'a change goes into the save: ' + JSON.stringify(save.deck.slots));
  deckSlot('SP3', 'SPL'); buildScene(performance.now(), false);
  check(save.deck.slots.SPL === 'SP3', 'and back');
  deckUpgrade3(); check(DECK.mk === 2 && !legacyLv('deck3'), 'mk III waits for ELITE');
  for (const k of ['drops', 'locker', 'bench']) save.legacy[k] = 1;
  check(boardLevel() === 3, 'ELITE');
  deckFuseIn(); check(!legacyLv('fuse'), 'the FUSE needs mk III first');
  const r0 = save.rep; deckUpgrade3();
  check(DECK.mk === 3 && legacyLv('deck3') === 1 && save.rep === r0 - deckCost('deck3'), 'mk III is THE BOARD post, at its price: ' + (r0 - save.rep));
  save.legacy.elite1 = 1; check(boardLevel() === 4, 'SYSOP (mk III and a placeholder)');
  deckFuseIn(); check(DECK.mk === 4 && DECK.fuse && legacyLv('fuse') === 1, 'the FUSE: mk IV');
  check(LEGACY.filter(u => u.placeholder && u.tier === 3).length === 3 && LEGACY.filter(u => u.placeholder && u.tier === 4).length === 3, 'placeholder posts on ELITE and SYSOP');
  // the switches: STRAY off turns the post off for runs
  save.legacy.stray = 1; openDeck(); await sleep(200);
  check(deckSwitches().join() === 'stray' && postOn('stray'), 'only the posts you own are settings: ' + deckSwitches());
  DECK.sw.delete('stray'); buildScene(performance.now(), false);
  check(!postOn('stray') && save.deck.off.includes('stray'), 'switched off: postOn says no');
  DECK.bits = [0, 0, 0, 0, 1, 1, 1, 1]; deckEnterByte(); buildScene(performance.now(), false);
  check(save.deck.overclock === true && deckPower().budget === 15, 'OVERCLOCK stays on (saved)');
  DECK.bits = [0, 0, 0, 0, 1, 1, 1, 1]; deckEnterByte(); buildScene(performance.now(), false);
  check(save.deck.overclock === false, 'entering it again turns it off');
  wipeProgress(); check(save.deck === null, 'a progression wipe takes the deck too');
  // ---- chips as loot: gear in your belt, kept out of the random pools, home when you cash out
  check(ITEMS.chip_DM5 && ITEMS.chip_DM5.chip === 'DM5' && !gearAllowed('chip_DM5'), 'every chip is gear, kept out of the drop pools');
  check(!shopGear().some(k => ITEMS[k].chip) && !lootPool().some(k => ITEMS[k].chip), 'no chips in markets or loot');
  save.legacy = { hard: 1, cash: 1, kit: 1, belt: 1 }; save.deck = null; CALL_QUEUE.length = 0; deckEnsure(); CALL_QUEUE.length = 0; FEAT_QUEUE.length = 0;
  B.startRun('CHIPTEST', false); await settle('chip run');
  st.run.items = [];
  let nid = null; for (let i = 0; i < 300 && !nid; i++) { const r = rngFor(st.run.seed, 'cachechip', 'n' + i); if (r() < DECK_DROP.cache) nid = 'n' + i; }
  const line = deckCacheChip({ id: nid }), got = st.run.items.find(x => ITEMS[x.key].chip);
  check(line && got, 'a DATA CACHE can drop a chip into your belt: ' + line);
  check(beltLabel(got).length === 5 && beltLabel(got)[0] === '[' && beltLabel(got)[4] === ']' && /NEW/.test(itemView(got.key).tip), 'on the belt: its face, 3 wide; its tip says NEW: ' + beltLabel(got) + ' / ' + itemView(got.key).tip);
  check(whyNotItem(got) === 'a chip: CASH OUT to keep it.' && !canUse(got), "it can't be used in a run");
  check(shredCode({ kind: 'gear', key: got.key }).length >= 1, 'the bench can shred it: ' + shredCode({ kind: 'gear', key: got.key }));
  const ck = ITEMS[got.key].chip;
  deckHome(st.run, false); check(!deckHave(ck), 'die: it never gets home');
  deckHome(st.run, true); check(deckHave(ck) === 1 && FEAT_QUEUE.some(q => q.head === 'YOUR DECK'), 'cash out: it goes home to your deck: ' + ck);
  check(/dupe: you have 1/.test(itemView(got.key).tip), 'another one says it is a dupe');
  st.run.items = []; for (let i = 0; i < st.run.beltSlots; i++) st.run.items.push({ key: 'patch', tier: 0, n: 1 });
  deckCacheChip({ id: nid }); await sleep(50);
  check(st.swap && st.swap.kind === 'item' && ITEMS[st.swap.key].chip, 'a full belt: the swap comes up');
  st.swap = null; FEAT_QUEUE.length = 0;
  const fo = deckFishChip({ kind: 'gear', key: 'patch', tier: 0 }, { node: { id: 'p1' } });
  check(fo.kind === 'gear' && (fo.key === 'patch' || ITEMS[fo.key].chip), 'the PIER: a gear catch is gear or a chip');
  DECK = null; Object.keys(save).forEach(k => delete save[k]); Object.assign(save, JSON.parse(keep)); persist();
` };
